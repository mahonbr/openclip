#!/usr/bin/env python3
"""Materialize the `.swiftrun` scratch package used by `scripts/dev_swift_run.sh`.

A literal single-file flattening of the app is not possible: `Core` and
`OpenSelection` declare the same type names (`CursorClass`, `LogLevel`, ...) and
`OpenSelectionBridge` disambiguates them with module qualifiers. Concatenating
the sources would collide on those names (and on 125 file-private declarations),
so the runner aggregates at the module level instead: it mirrors both targets
into a throwaway SwiftPM package, builds one dynamic library, and lets `swift`
JIT-load it. No executable is ever written to disk.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

# identity in Package.resolved -> (repository URL, product name, package identity)
DIRECT_PACKAGES = {
    "openselection": ("https://github.com/ganeshmshetty/OpenSelection.git", "OpenSelection", "OpenSelection"),
    "keyboardshortcuts": ("https://github.com/sindresorhus/KeyboardShortcuts", "KeyboardShortcuts", "KeyboardShortcuts"),
    "sdwebimageswiftui": ("https://github.com/SDWebImage/SDWebImageSwiftUI", "SDWebImageSwiftUI", "SDWebImageSwiftUI"),
    "sdwebimagesvgcoder": ("https://github.com/SDWebImage/SDWebImageSVGCoder", "SDWebImageSVGCoder", "SDWebImageSVGCoder"),
    "sparkle": ("https://github.com/sparkle-project/Sparkle", "Sparkle", "Sparkle"),
    "swift-markdown-ui": ("https://github.com/gonzalezreal/swift-markdown-ui", "MarkdownUI", "swift-markdown-ui"),
}

# Used only when the Xcode project has no Package.resolved (fresh clone).
FALLBACK_VERSIONS = {
    "openselection": "2.16.5",
    "keyboardshortcuts": "3.1.0",
    "sdwebimageswiftui": "3.1.4",
    "sdwebimagesvgcoder": "1.8.0",
    "sparkle": "2.10.1",
    "swift-markdown-ui": "2.4.1",
}

PACKAGE_RESOLVED = Path(
    "OpenClip.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved"
)

MANIFEST = """// swift-tools-version: 6.0
// Generated by scripts/swiftrun/prepare.py. Do not edit by hand.
import PackageDescription

let package = Package(
    name: "OpenClipSwiftRun",
    platforms: [.macOS(.v14)],
    products: [
        .library(name: "OpenClip", type: .dynamic, targets: ["OpenClip"])
    ],
    dependencies: [
{dependencies}
    ],
    targets: [
        .target(
            name: "Core",
            path: "Sources/Core",
            swiftSettings: [.swiftLanguageMode(.v6), .define("DEBUG")]
        ),
        .target(
            name: "OpenClip",
            dependencies: [
                "Core",
{products}
            ],
            path: "Sources/OpenClip",
            exclude: ["Resources", "Info.plist", "OpenClip.entitlements"],
            swiftSettings: [.swiftLanguageMode(.v6), .define("DEBUG")]
        )
    ]
)
"""


def resolved_versions(root: Path) -> dict[str, str]:
    path = root / PACKAGE_RESOLVED
    if not path.is_file():
        return dict(FALLBACK_VERSIONS)
    pins = json.loads(path.read_text(encoding="utf-8")).get("pins", [])
    versions = dict(FALLBACK_VERSIONS)
    for pin in pins:
        identity = pin.get("identity", "")
        version = pin.get("state", {}).get("version")
        if identity in DIRECT_PACKAGES and version:
            versions[identity] = version
    return versions


def render_manifest(versions: dict[str, str]) -> str:
    dependencies = "\n".join(
        f'        .package(url: "{DIRECT_PACKAGES[identity][0]}", exact: "{versions[identity]}"),'
        for identity in DIRECT_PACKAGES
    )
    products = "\n".join(
        f'                .product(name: "{DIRECT_PACKAGES[identity][1]}", package: "{DIRECT_PACKAGES[identity][2]}"),'
        for identity in DIRECT_PACKAGES
    )
    return MANIFEST.format(dependencies=dependencies, products=products)


def write_if_changed(path: Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def patched(source: Path, patches: list[dict[str, str]]) -> bytes:
    data = source.read_bytes()
    if not patches:
        return data
    text = data.decode("utf-8")
    for patch in patches:
        if patch["find"] in text:
            if text.count(patch["find"]) != 1:
                sys.exit(
                    f"error: patch anchor in {patch['file']} matched "
                    f"{text.count(patch['find'])} times; expected exactly one"
                )
            text = text.replace(patch["find"], patch["replace"], 1)
        elif patch["replace"] not in text:
            sys.exit(
                f"error: patch anchor no longer exists in {patch['file']}:\n"
                f"  {patch['find'].splitlines()[0]}"
            )
    return text.encode("utf-8")


def sync_tree(
    src: Path,
    dst: Path,
    target_name: str,
    keep: set[str],
    patches: dict[str, list[dict[str, str]]],
) -> int:
    """Mirror `src` into `dst`, applying dev patches and preserving source mtimes."""
    dst.mkdir(parents=True, exist_ok=True)
    wanted = {path.relative_to(src) for path in src.rglob("*") if path.is_file()}
    for path in dst.rglob("*"):
        relative = path.relative_to(dst)
        if path.is_file() and relative not in wanted and str(relative) not in keep:
            path.unlink()
    for directory in sorted((p for p in dst.rglob("*") if p.is_dir()), reverse=True):
        try:
            directory.rmdir()
        except OSError:
            pass

    changed = 0
    for relative in sorted(wanted):
        source = src / relative
        target = dst / relative
        content = patched(source, patches.get(f"Sources/{target_name}/{relative.as_posix()}", []))
        if target.is_file() and target.read_bytes() == content:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        changed += 1
    return changed


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("usage: prepare.py <repo-root> <scratch-dir>")
    root = Path(sys.argv[1]).resolve()
    scratch = Path(sys.argv[2]).resolve()
    templates = root / "scripts" / "swiftrun"
    for name in ("Core", "OpenClip"):
        if not (root / "Sources" / name).is_dir():
            sys.exit(f"error: missing Sources/{name}")
    if not (templates / "patches.json").is_file():
        sys.exit(f"error: missing {templates / 'patches.json'}")

    patches = json.loads((templates / "patches.json").read_text(encoding="utf-8"))
    by_file: dict[str, list[dict[str, str]]] = {}
    for patch in patches:
        by_file.setdefault(patch["file"], []).append(patch)

    keep = {"DevRunEntry.swift"}
    changed = sync_tree(root / "Sources" / "Core", scratch / "Sources" / "Core", "Core", keep, by_file)
    changed += sync_tree(
        root / "Sources" / "OpenClip", scratch / "Sources" / "OpenClip", "OpenClip", keep, by_file
    )

    write_if_changed(scratch / "Package.swift", render_manifest(resolved_versions(root)))
    write_if_changed(scratch / "App.swift", (templates / "App.swift").read_text(encoding="utf-8"))
    write_if_changed(
        scratch / "Sources" / "OpenClip" / "DevRunEntry.swift",
        (templates / "DevRunEntry.swift").read_text(encoding="utf-8"),
    )

    if changed:
        print(f"Mirrored {changed} changed source file(s)", file=sys.stderr)


if __name__ == "__main__":
    main()
